"""
Render aggregated baseline results to markdown + CSV.

Results structure (produced by run_baseline.py):
{
  "config": {...},
  "overall": {"n_tiles": int, "scale_invariant": {metric: val}, "metric_as_app": {metric: val}},
  "per_city": {city: {"n_tiles": int, "scale_invariant": {...}, "metric_as_app": {...}}},
}
"""
from __future__ import annotations

import csv
import math
from pathlib import Path

SI_METRICS = ["aligned_rmse", "si_rmse", "aligned_mae", "aligned_delta1", "aligned_tall_mae", "boundary_f"]
APP_METRICS = ["rmse", "mae", "delta1", "tall_mae", "boundary_f"]

_LABELS = {
    "aligned_rmse": "Aligned RMSE (m)",
    "si_rmse": "SI-RMSE (log)",
    "aligned_mae": "Aligned MAE (m)",
    "aligned_delta1": "Aligned δ1",
    "aligned_tall_mae": "Aligned tall MAE (m)",
    "rmse": "RMSE (m)",
    "mae": "MAE (m)",
    "delta1": "δ1",
    "tall_mae": "Tall MAE (m)",
    "boundary_f": "Boundary-F",
}


def _fmt(v) -> str:
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "n/a"
    return f"{v:.4f}"


def _block_table(block: dict, keys: list[str]) -> str:
    rows = [f"| {_LABELS.get(k, k)} | {_fmt(block.get(k))} |" for k in keys]
    return "| Metric | Value |\n|---|---|\n" + "\n".join(rows)


def write_reports(results: dict, out_dir: Path) -> tuple[Path, Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    md_path = out_dir / "baseline_report.md"
    csv_path = out_dir / "baseline_metrics.csv"

    cfg = results.get("config", {})
    overall = results["overall"]

    lines: list[str] = []
    lines.append("# DepthWizard P0 — Baseline (current pipeline)\n")
    lines.append("> Auto-generated by `upgrade/evaluation/run_baseline.py`. "
                 "This is the **BEFORE** table every later phase is judged against.\n")
    lines.append("## Run configuration\n")
    for k, v in cfg.items():
        lines.append(f"- **{k}**: {v}")
    lines.append("")
    lines.append("## What the two blocks mean\n")
    lines.append("- **Scale-invariant** — the prediction is best-fit aligned (scale+shift) to the "
                 "ground truth first. Measures the model's *shape* quality, fair to a relative model.")
    lines.append("- **Metric as-shipped** — the current `calibration.py` converts the relative "
                 "output to meters, compared directly to LiDAR meters. Exposes calibration error.\n")

    lines.append(f"## Overall ({overall['n_tiles']} tiles)\n")
    lines.append("### Scale-invariant (model shape quality)\n")
    lines.append(_block_table(overall["scale_invariant"], SI_METRICS))
    lines.append("\n### Metric as-shipped (current calibration)\n")
    lines.append(_block_table(overall["metric_as_app"], APP_METRICS))
    lines.append("")

    per_city = results.get("per_city", {})
    if per_city:
        lines.append("## Per-city (unseen-geography breakdown)\n")
        lines.append("| City | Tiles | Aligned RMSE (m) | SI-RMSE | Boundary-F | As-shipped RMSE (m) | As-shipped MAE (m) |")
        lines.append("|---|---|---|---|---|---|---|")
        for city in sorted(per_city):
            c = per_city[city]
            si, ap = c["scale_invariant"], c["metric_as_app"]
            lines.append(
                f"| {city} | {c['n_tiles']} | {_fmt(si.get('aligned_rmse'))} | "
                f"{_fmt(si.get('si_rmse'))} | {_fmt(si.get('boundary_f'))} | "
                f"{_fmt(ap.get('rmse'))} | {_fmt(ap.get('mae'))} |"
            )
        lines.append("")

    md_path.write_text("\n".join(lines), encoding="utf-8")

    # CSV: one row per (scope, block).
    with csv_path.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        header = ["scope", "block", "n_tiles"] + sorted(set(SI_METRICS + APP_METRICS))
        w.writerow(header)

        def _row(scope, block_name, n_tiles, block):
            row = [scope, block_name, n_tiles]
            for m in sorted(set(SI_METRICS + APP_METRICS)):
                v = block.get(m)
                row.append("" if v is None or (isinstance(v, float) and math.isnan(v)) else f"{v:.6f}")
            return row

        w.writerow(_row("overall", "scale_invariant", overall["n_tiles"], overall["scale_invariant"]))
        w.writerow(_row("overall", "metric_as_app", overall["n_tiles"], overall["metric_as_app"]))
        for city in sorted(per_city):
            c = per_city[city]
            w.writerow(_row(city, "scale_invariant", c["n_tiles"], c["scale_invariant"]))
            w.writerow(_row(city, "metric_as_app", c["n_tiles"], c["metric_as_app"]))

    return md_path, csv_path
